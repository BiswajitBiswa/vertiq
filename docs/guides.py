def snippet(g: dict) -> str:
    """The guide's reference implementation: mapping, a plugin, the analyses and the rules.
    tests/test_guides.py executes every one of these against generated records."""
    import json
    mp = json.dumps(g["mapping"], ensure_ascii=False).replace("null", "None")
    p, ev, val = g["plugin"], g["event"], g["value"]
    lines = ["from datetime import datetime, timedelta",
             "from vertiq import plugins, rules",
             "from vertiq.mapping import Mapping, apply, repair",
             "from vertiq.tasks import predict_event, predict_value",
             "",
             "# rows: the source export as a list of dicts, e.g. list(csv.DictReader(open(\"export.csv\")))",
             f"mapping = Mapping.parse({mp})",
             "m, notes = repair(mapping, rows)      # validates column names, value types and date format against the rows",
             "ds, problems = apply(m, rows)         # rows that fail to load are reported, not imputed",
             "",
             f"@plugins.feature(\"{p['pack']}\")",
             f"def {p['name']}(entity, before, cut):   # receives only events recorded before the cutoff",
             p["body"],
             "",
             f"task = predict_event(ds, target=\"{ev['target']}\", window_days={ev['window']}, pack=\"{p['pack']}\")",
             "print(task.status, task.report())     # \"trained\" only if the model outperformed the baseline on held-out entities",
             "if task.status == \"trained\":",
             f"    print(task.score(\"{ev['id']}\"))  # probability with contributing factors"]
    if val:
        lines += ["",
                  f"size = predict_value(ds, target=\"{val['target']}\", window_days={val['window']}, pack=\"{p['pack']}\")",
                  "print(size.status, size.report())"]
    if g["rules"]:
        lines += ["", "flags = rules.run(ds, ["] + [f"    rules.{r},   # {why}" for r, why in g["rules"]] + ["])",
                  "print(flags[\"summary\"])"]
    return "\n".join(lines)

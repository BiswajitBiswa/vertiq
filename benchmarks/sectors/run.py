"""Sector benchmark: Vertiq's one-command report on public data from five sectors, nothing tuned per sector.

  benchmarks/sectors/fetch.sh                  # download the public data (about 160 MB, git-ignored)
  python benchmarks/sectors/run.py [--only food_safety] [--jobs 5]

Each sector's config (configs/*.json) names only the files, the words to use and, where the outcome is a value
in a column, the outcome ("Fail"). Vertiq proposes the mapping, finds patterns, and trains predictions through
its evaluation gate, as `vertiq-report` does for a client. The full reports go to reports/<sector>.md and the
figures to benchmarks/results/sectors.json, which the documentation site reads.
"""
from __future__ import annotations

import argparse
import json
import os
import platform
import sys
import time
from concurrent.futures import ProcessPoolExecutor
from datetime import date
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent.parent
sys.path.insert(0, str(ROOT))

SECTORS = {
    "retail": {"title": "Retail", "dataset": "UCI Online Retail II: a UK online shop's invoice lines, 2009-2010",
               "source": "https://archive.ics.uci.edu/dataset/502/online+retail+ii", "terms": "CC BY 4.0",
               "question": "Will a customer buy again, and how much?"},
    "food_safety": {"title": "Food safety", "dataset": "City of Chicago food inspections since 2019 (up to 150,000)",
                    "source": "https://data.cityofchicago.org/Health-Human-Services/Food-Inspections/4ijn-s7e5",
                    "terms": "City of Chicago open data terms", "question": "Which establishments will fail an inspection?"},
    "animal_services": {"title": "Animal services", "dataset": "Austin Animal Center intakes (up to 200,000)",
                        "source": "https://data.austintexas.gov/Health-and-Community-Services/Austin-Animal-Center-Intakes/wter-evkm",
                        "terms": "City of Austin open data", "question": "Which animals will come back to the shelter?"},
    "manufacturing": {"title": "Manufacturing", "dataset": "Microsoft Azure predictive maintenance sample: 100 machines, 2015 (errors, failures, machine models)",
                      "source": "https://github.com/NVIDIA/GenerativeAIExamples/tree/main/RAG/examples/advanced_rag/structured_data_rag/data",
                      "terms": "public sample data", "question": "Which machines will fail?"},
    "transport": {"title": "Transport", "dataset": "NYC motor vehicle collisions since January 2025 (up to 200,000)",
                  "source": "https://data.cityofnewyork.us/Public-Safety/Motor-Vehicle-Collisions-Crashes/h9gi-nx95",
                  "terms": "NYC open data terms", "question": "Where will collisions happen again?"},
}


def one(name: str) -> dict:
    from vertiq import report
    cfg_path = HERE / "configs" / f"{name}.json"
    config = json.loads(cfg_path.read_text())
    collect: dict = {}
    started = time.time()
    text = report.run(config, cfg_path.parent, collect)
    seconds = round(time.time() - started, 1)
    (HERE / "reports").mkdir(exist_ok=True)
    (HERE / "reports" / f"{name}.md").write_text(f"<!-- {SECTORS[name]['dataset']} · generated by benchmarks/sectors/run.py -->\n" + text)
    preds = []
    for r in collect.get("predictions", []):
        m = r.get("metrics") or {}
        segs = m.get("segments") or []
        preds.append({"task": r["task"], "target": r["target"], "window_days": r.get("window_days"), "status": r["status"],
                      "held_out": m.get("entities_held_out"), "metric": "AUC" if "auc" in m else ("MAE" if "mae" in m else None),
                      "model": m.get("auc", m.get("mae")), "baseline": m.get("baseline_auc", m.get("baseline_mae")),
                      "gain_ci": (m.get("intervals") or {}).get("gain_ci"), "segments_checked": len(segs),
                      "segments_worse": [f"{s['dimension']} {s['label']}" for s in segs if s["worse"]],
                      "need_rows": r.get("need_rows"), "rows": r.get("rows", m.get("rows"))})
    mapping = next((x.split("Mapping used: ", 1)[1] for x in collect.get("log", []) if "Mapping used: " in x), None)
    return {"name": name, **SECTORS[name], "records": collect.get("records"), "entities": collect.get("entities"),
            "mapping": mapping, "patterns": collect.get("patterns"), "combos": collect.get("combos", [])[:3],
            "predictions": preds, "seconds": seconds}


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--only", default="", help="comma-separated sectors")
    ap.add_argument("--jobs", type=int, default=len(SECTORS))
    a = ap.parse_args()
    names = [n for n in SECTORS if not a.only or n in a.only.split(",")]
    missing = [n for n in names if not (HERE / "configs" / f"{n}.json").exists()]
    if missing:
        raise SystemExit(f"no config for {missing}")
    started = time.time()
    with ProcessPoolExecutor(max_workers=min(a.jobs, len(names))) as pool:
        results = list(pool.map(one, names))
    out = ROOT / "benchmarks" / "results" / "sectors.json"
    old = json.loads(out.read_text()) if out.exists() and a.only else {"sectors": []}
    merged = {s["name"]: s for s in old.get("sectors", [])} | {r["name"]: r for r in results}
    doc = {"generated": str(date.today()), "machine": f"{platform.machine()}, {os.cpu_count()} cores",
           "python": platform.python_version(), "wall_seconds": round(time.time() - started, 1),
           "sectors": [merged[n] for n in SECTORS if n in merged]}
    out.write_text(json.dumps(doc, indent=1, ensure_ascii=False) + "\n")
    for r in results:
        promoted = [f"{p['target']} {p['window_days']}d" for p in r["predictions"] if p["status"] == "trained"]
        print(f"{r['title']:<16} {r['records']:>8} records  {r['entities']:>7} entities  promoted: {', '.join(promoted) or 'none'}  ({r['seconds']}s)")
    print(f"wrote {out}")


if __name__ == "__main__":
    main()

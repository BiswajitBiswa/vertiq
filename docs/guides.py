def snippet(g: dict) -> str:
    """The guide's working example: mapping, a plugin, the questions and the rules. tests/test_guides.py
    runs every one of these against generated rows, so the code in the docs is known to work."""
    import json
    mp = json.dumps(g["mapping"], ensure_ascii=False).replace("null", "None")
    p, ev, val = g["plugin"], g["event"], g["value"]
    lines = ["from datetime import datetime, timedelta",
             "from vertiq import plugins, rules",
             "from vertiq.mapping import Mapping, apply, repair",
             "from vertiq.tasks import predict_event, predict_value",
             "",
             "# rows: your export as a list of dicts, e.g. list(csv.DictReader(open(\"export.csv\")))",
             f"mapping = Mapping.parse({mp})",
             "m, notes = repair(mapping, rows)      # the rows settle column names, value types and the date format",
             "ds, problems = apply(m, rows)         # any row that didn't load is named, never guessed",
             "",
             f"@plugins.feature(\"{p['pack']}\")",
             f"def {p['name']}(entity, before, cut):   # only events before the cutoff: no peeking",
             p["body"],
             "",
             f"task = predict_event(ds, target=\"{ev['target']}\", window_days={ev['window']}, pack=\"{p['pack']}\")",
             "print(task.status, task.report())     # \"trained\" only if it beat the baseline on held-out entities",
             "if task.status == \"trained\":",
             f"    print(task.score(\"{ev['id']}\"))  # the chance, and what raises or lowers it"]
    if val:
        lines += ["",
                  f"size = predict_value(ds, target=\"{val['target']}\", window_days={val['window']}, pack=\"{p['pack']}\")",
                  "print(size.status, size.report())"]
    if g["rules"]:
        lines += ["", "flags = rules.run(ds, ["] + [f"    rules.{r},   # {why}" for r, why in g["rules"]] + ["])",
                  "print(flags[\"summary\"])"]
    return "\n".join(lines)
